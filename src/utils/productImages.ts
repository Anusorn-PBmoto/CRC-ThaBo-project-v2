// Normalize text for fuzzy comparison
function normalizeString(str: string): string {
  return str
    .toLowerCase()
    .replace(/[._\-/\s]+/g, "")
    .trim();
}

export function resolveProductImage(item?: Partial<ProductItem> | null): string {
  if (!item) return "";
  if (item.imageUrl && item.imageUrl.trim() !== "") {
    return item.imageUrl;
  }
  if (item.id && RECOVERED_PRODUCT_IMAGES[item.id]) {
    return RECOVERED_PRODUCT_IMAGES[item.id];
  }
  if (item.barcode && RECOVERED_PRODUCT_IMAGES[item.barcode]) {
    return RECOVERED_PRODUCT_IMAGES[item.barcode];
  }
  if (item.name && RECOVERED_PRODUCT_IMAGES[item.name]) {
    return RECOVERED_PRODUCT_IMAGES[item.name];
  }
  if (item.size && RECOVERED_PRODUCT_IMAGES[item.size]) {
    return RECOVERED_PRODUCT_IMAGES[item.size];
  }

  // Normalized name match fallback
  const normalizedItemName = normalizeString(item.name || item.size || "");
  if (normalizedItemName) {
    for (const [key, url] of Object.entries(RECOVERED_PRODUCT_IMAGES)) {
      if (normalizeString(key) === normalizedItemName) {
        return url;
      }
    }
  }

  return "";
}

export interface MatchResult {
  product: ProductItem | null;
  matchType: "id" | "barcode" | "name" | "none";
  matchLabel: string;
  confidence: number;
}

/**
 * Automatically matches an image file name to a product using:
 * 1. Product ID (รหัสสินค้า)
 * 2. Barcode / QR Code (รหัสบาร์โค้ด / คิวอาร์โค้ด)
 * 3. Product Name or Size (ชื่อสินค้า)
 */
export function matchImageFileNameToProduct(
  fileName: string,
  products: ProductItem[]
): MatchResult {
  if (!fileName || !products || products.length === 0) {
    return { product: null, matchType: "none", matchLabel: "ไม่พบสินค้าที่ตรงกัน", confidence: 0 };
  }

  const baseName = fileName.replace(/\.[^/.]+$/, "").trim();
  const normalizedBase = normalizeString(baseName);

  // 1. Try matching with Product ID
  for (const p of products) {
    if (p.id) {
      if (baseName === p.id || baseName.startsWith(p.id + "_") || baseName.includes(p.id)) {
        return {
          product: p,
          matchType: "id",
          matchLabel: "ตรงกับรหัสสินค้า (" + p.id.slice(0, 10) + "...)",
          confidence: 1.0,
        };
      }
    }
  }

  // 2. Try matching with Barcode / QR Code
  for (const p of products) {
    if (p.barcode && p.barcode.trim().length >= 4) {
      const code = p.barcode.trim();
      if (baseName === code || baseName.includes(code)) {
        return {
          product: p,
          matchType: "barcode",
          matchLabel: "ตรงกับคิวอาร์/บาร์โค้ด (" + code + ")",
          confidence: 0.95,
        };
      }
    }
  }

  // 3. Try matching with Product Name or Size
  for (const p of products) {
    const rawName = p.name || p.size || "";
    if (!rawName) continue;

    const normName = normalizeString(rawName);
    if (!normName) continue;

    if (
      normalizedBase === normName ||
      normalizedBase.includes(normName) ||
      normName.includes(normalizedBase)
    ) {
      return {
        product: p,
        matchType: "name",
        matchLabel: "ตรงกับชื่อสินค้า (" + rawName + ")",
        confidence: 0.9,
      };
    }
  }

  return { product: null, matchType: "none", matchLabel: "ยังไม่พบสินค้าที่ตรงกัน", confidence: 0 };
}
